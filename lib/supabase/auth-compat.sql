create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text,
  password text,
  salt text,
  name text,
  role text not null default 'admin',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  token_version integer
);

alter table public.admin_users add column if not exists password_hash text;
alter table public.admin_users add column if not exists password text;
alter table public.admin_users add column if not exists salt text;
alter table public.admin_users add column if not exists name text;
alter table public.admin_users add column if not exists role text default 'admin';
alter table public.admin_users add column if not exists is_active boolean default true;
alter table public.admin_users add column if not exists created_at timestamptz default now();
alter table public.admin_users add column if not exists token_version integer;

create unique index if not exists admin_users_email_lower_idx
  on public.admin_users (lower(email));

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text,
  password text,
  salt text,
  name text,
  role text not null default 'user',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  token_version integer
);

alter table public.users add column if not exists password_hash text;
alter table public.users add column if not exists password text;
alter table public.users add column if not exists salt text;
alter table public.users add column if not exists name text;
alter table public.users add column if not exists role text default 'user';
alter table public.users add column if not exists is_active boolean default true;
alter table public.users add column if not exists created_at timestamptz default now();
alter table public.users add column if not exists updated_at timestamptz;
alter table public.users add column if not exists token_version integer;

create unique index if not exists users_email_lower_idx
  on public.users (lower(email));
