async function main() {
  const existing = await rest('taxonomies?select=id,kind,lang,slug,name,icon');
  const key = (t) => `${t.kind}|${t.lang}|${t.slug}`;
  const have = new Set(existing.map(key));

  const newTax = [];
  NEW_SUBBRANCHES.forEach(([slug, name, icon], i) => {
    if (!have.has(`subbranch|ar|${slug}`)) {
      newTax.push({ id: detUuid(`taxonomy:sub:${slug}`), kind: 'subbranch', lang: 'ar', name, slug, icon, color: null, sort_order: 100 + i });
    }
  });
  for (const f of NEW_FIELDS) {
    if (!have.has(`field|ar|${f.slug}`)) {
      newTax.push({ id: detUuid(`taxonomy:field:ar:${f.slug}`), kind: 'field', lang: 'ar', name: f.ar, slug: f.slug, icon: f.icon, color: null, sort_order: 100 });
    }
    if (!have.has(`field|en|${f.slug}`)) {
      newTax.push({ id: detUuid(`taxonomy:field:en:${f.slug}`), kind: 'field', lang: 'en', name: f.en, slug: f.slug, icon: f.icon, color: null, sort_order: 100 });
    }
  }

  // خريطة المجالات (ar) للربط
  const fieldIdBySlug = new Map(
    existing.filter((t) => t.kind === 'field' && t.lang === 'ar').map((t) => [t.slug, t.id])
  );

  const contents = [];
  const translations = [];
  const terms = [];
  CONTENT.forEach((c, i) => {
    const id = detUuid(`content:${c.type}:${c.slug}`);
    contents.push({
      id,
      content_type: c.type,
      status: 'published',
      lang_original: 'ar',
      audience: ['muslim_general', 'non_muslim'],
      age_groups: ['all'],
      levels: ['beginner', 'intermediate'],
      madhhabs: ['general'],
      sort_order: i,
      published_at: new Date().toISOString(),
      views: 0,
      needs_scholar_review: false,
    });
    translations.push({
      content_id: id,
      lang: 'ar',
      slug: c.slug,
      title: c.title,
      summary: c.summary,
      body: c.body,
      body_plain: c.body.replace(/\*\*/g, ''),
      is_machine_translated: false,
      is_reviewed: true,
    });
    const taxId = fieldIdBySlug.get(c.field);
    if (taxId) terms.push({ content_id: id, taxonomy_id: taxId });
    else console.warn(`⚠ لا يوجد تصنيف field لهذا المحتوى: ${c.field}`);
  });

  console.log('=== خطة المرحلة 2 + 4 ===');
  console.log(`تصنيفات جديدة: ${newTax.length}`);
  console.log(`عناصر محتوى: ${contents.length}`);
  console.log(`ترجمات: ${translations.length}`);
  console.log(`ربط بالتصنيفات: ${terms.length}`);
  const byField = {};
  for (const c of CONTENT) byField[c.field] = (byField[c.field] ?? 0) + 1;
  console.log('التوزيع:', JSON.stringify(byField));

  if (!COMMIT) {
    console.log('\n(معاينة فقط) للتنفيذ: --commit');
    return;
  }

  await upsert('taxonomies', newTax, 'kind,lang,slug');
  await upsert('content', contents, 'id');
  await upsert('content_translations', translations, 'content_id,lang');
  await upsert('content_terms', terms, 'content_id,taxonomy_id');
  console.log('✔ تم التنفيذ بنجاح.');
}

main().catch((err) => {
  console.error('✖ فشل:', err.message);
  process.exit(1);
});
